/// The installer stages files in the user's LocalAppData. Never launch that
/// user-writable helper with an elevated token.
void requireUnelevatedUpdater() => using((arena) {
  final handle = arena<Pointer>();
  if (!OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, handle).value) {
    throw const UpdateException(
      'Could not check Windows permissions. Update manually from the releases page.',
    );
  }
  try {
    final elevation = arena<TOKEN_ELEVATION>();
    final returned = arena<Uint32>();
    if (!GetTokenInformation(
          HANDLE(handle.value),
          TokenElevation,
          elevation,
          sizeOf<TOKEN_ELEVATION>(),
          returned,
        ).value ||
        returned.value < sizeOf<TOKEN_ELEVATION>()) {
      throw const UpdateException(
        'Could not check Windows permissions. Update manually from the releases page.',
      );
    }
    if (elevation.ref.TokenIsElevated != 0) {
      throw const UpdateException(
        'This app is running as administrator. Update manually from the releases page.',
      );
    }
  } finally {
    CloseHandle(HANDLE(handle.value));
  }
});

/// Reads the version resource generated by Flutter's Windows build.
AgentVersion windowsAgentVersion(String executable) => using((arena) {
  final path = PCWSTR(executable.toNativeUtf16(allocator: arena));
  final length = GetFileVersionInfoSize(path, nullptr).value;
  if (length != 0) {
    final bytes = arena<Uint8>(length);
    final result = arena<Pointer>();
    final size = arena<Uint32>();
    if (GetFileVersionInfo(path, length, bytes).value &&
        VerQueryValue(
          bytes,
          PCWSTR(r'\'.toNativeUtf16(allocator: arena)),
          result,
          size,
        ) &&
        size.value >= sizeOf<VS_FIXEDFILEINFO>()) {
      final version = result.value.cast<VS_FIXEDFILEINFO>().ref;
      if (version.dwSignature == 0xfeef04bd) {
        return AgentVersion(
          version.dwProductVersionMS >> 16,
          version.dwProductVersionMS & 0xffff,
          version.dwProductVersionLS >> 16,
        );
      }
    }
  }
  throw const UpdateException('The installed version could not be read.');
});

void openAgentReleasesPage() => using((arena) {
  final result = ShellExecute(
    null,
    PCWSTR('open'.toNativeUtf16(allocator: arena)),
    PCWSTR(agentReleasesPage.toString().toNativeUtf16(allocator: arena)),
    null,
    null,
    SW_SHOWNORMAL,
  );
  if (result.address <= 32) {
    throw const UpdateException('Open the releases page in your browser.');
  }
});
